//! HTTP/3 request throughput benchmark: QUIC, TLS 1.3 and QPACK all in the path.
//!
//! ```
//! zig build bench-http3_bench                      # 4 connections, 8 requests in flight each
//! zig build bench-http3_bench -- 4 8 5             # connections, in-flight, seconds
//! ./zig-out/bin/http3_bench server 4433 20         # serve only: port, seconds
//! ./zig-out/bin/http3_bench client 4433 4 8 5      # load only: port, connections, flight, secs
//! ```
//!
//! **This one cannot keep the framework out of the load generator, and that changes what the
//! number means.** `http_bench` and `http2_bench` generate load over raw sockets, so their
//! figures are the server's cost. A raw-socket QUIC client would be a second QUIC
//! implementation — packet protection, loss recovery, a TLS 1.3 handshake — so the load here is
//! generated by *this* stack. The result is therefore a **round trip through two Zinet QUIC
//! endpoints on one machine**, not a server capacity, and it should be read as the cost of the
//! whole protocol rather than of the server half. The interop tests against `aioquic` are what
//! establish correctness against another implementation; they are not a load test, because a
//! Python QUIC stack would be the bottleneck.
//!
//! What the number is good for anyway: it puts HTTP/3 on the same axis as the other two, which
//! is the question this file exists to answer — what does the extra machinery cost, in the same
//! process shape, on the same machine, with the same response body. And the split between the
//! handshake and the steady state is measurable here, since connections are established once and
//! then reused for thousands of requests.
//!
//! The certificate is the repository's own test identity, so the benchmark needs no files and no
//! setup; the client does not verify it, which removes chain validation from the steady-state
//! path but not the handshake's signature.
//!
//! Reported: requests per second, mean and worst-case latency, resets and refusals.

const std = @import("std");
const backend = @import("backend");
const zinet = @import("zinet");

const Io = std.Io;
const HandlerContext = zinet.HandlerContext;
const Message = zinet.Message;
const Pipeline = zinet.Pipeline;
const http3 = zinet.http3;
const qpack = http3.qpack;
const quic = zinet.quic;
const identity_mod = zinet.tls13.identity;

const log = std.log.scoped(.bench);

const Role = enum { both, server, client };

const Config = struct {
    role: Role = .both,
    connections: usize = 4,
    /// Requests in flight per connection. QUIC's `initial_max_streams_bidi` bounds this; the
    /// server here starts at 100 and issues more credit as streams complete.
    flight: usize = 8,
    duration_seconds: u64 = 3,
    port: u16 = 0,
    exe: []const u8 = &.{},
};

const server_prefix = "server:  ";

const response_body = "Hello from Zinet\n";

/// Answers one request stream, then ends that stream.
var answered: std.atomic.Value(u64) = .init(0);
var seen: std.atomic.Value(u64) = .init(0);

const Responder = struct {
    pub fn onRead(_: *Responder, ctx: *HandlerContext, msg: Message) !void {
        var owned = msg;
        defer owned.deinit(ctx.gpa());
        const headers = owned.get(http3.Headers) orelse return;
        if (headers.trailers) return;
        _ = seen.fetchAdd(1, .monotonic);

        var fields = [_]qpack.FieldLine{
            .{ .name = ":status", .value = "200" },
            .{ .name = "content-type", .value = "text/plain; charset=utf-8" },
            .{
                .name = "content-length",
                .value = std.fmt.comptimePrint("{d}", .{response_body.len}),
            },
        };
        try ctx.write(try Message.initAny(ctx.gpa(), http3.OutgoingHeaders, .{ .fields = &fields }));
        try ctx.write(try Message.initBytes(ctx.gpa(), response_body));
        try ctx.flush();
        try ctx.close();
        _ = answered.fetchAdd(1, .monotonic);
    }
};

fn buildStream(pipeline: *Pipeline) anyerror!void {
    const responder = try pipeline.gpa.create(Responder);
    responder.* = .{};
    errdefer pipeline.gpa.destroy(responder);
    _ = try pipeline.addLast("respond", .initOwned(responder));
}

const Result = struct {
    requests: u64 = 0,
    latency_sum_ns: u64 = 0,
    latency_max_ns: u64 = 0,
    resets: u64 = 0,
    /// Requests that could not be started because QUIC had no stream credit. Counted rather
    /// than retried silently: it is the boundary this benchmark is looking for.
    refused: u64 = 0,
    established: bool = false,
    /// Why the connection stopped, if it did. A benchmark that ignores these reports a low
    /// number as though it were a slow server, which is the harness lying rather than the
    /// server being slow — and this one did exactly that until a stall was traced by hand.
    closed: u64 = 0,
    timed_out: u64 = 0,
    goaway: u64 = 0,
};

/// One request in flight.
const InFlight = struct {
    stream: u64 = no_stream,
    started: Io.Timestamp = undefined,

    const no_stream: u64 = std.math.maxInt(u64);
};

/// Keeps a fixed number of requests in flight on one connection.
///
/// Every callback runs on the endpoint's reader task, which is what lets this hold plain fields:
/// the connection has exactly one reader, so there is nothing to synchronise against. `main`
/// reads `result` only after the client has been shut down.
const Load = struct {
    gpa: std.mem.Allocator,
    io: Io,
    host: []const u8,
    slots: []InFlight,
    deadline: Io.Timestamp,
    result: *Result,

    fn on(self: *Load, conn: *http3.client.Connection, event: http3.client.Event) void {
        switch (event) {
            .established => {
                self.result.established = true;
                self.topUp(conn);
            },
            .headers => |e| {
                var section = conn.takeSection(e.stream) orelse return;
                section.deinit(self.gpa);
                if (e.fin) self.complete(conn, e.stream);
            },
            .body => |e| {
                const bytes = conn.readBody(e.stream);
                conn.consumeBody(e.stream, bytes.len);
                if (e.fin) self.complete(conn, e.stream);
            },
            .stream_reset => |e| {
                self.result.resets += 1;
                self.release(e.stream);
                self.topUp(conn);
            },
            // The event this benchmark existed without and could not run without: the
            // peer raised the stream limit, so a request refused for want of credit
            // can be issued now. Nothing else can wake a connection whose every
            // stream has closed.
            .stream_credit => self.topUp(conn),
            .peer_closed => self.result.closed += 1,
            .idle_timeout => self.result.timed_out += 1,
            .goaway => self.result.goaway += 1,
            .datagram => {},
        }
    }

    fn complete(self: *Load, conn: *http3.client.Connection, stream: u64) void {
        const slot = self.find(stream) orelse return;
        const finished = Io.Timestamp.now(self.io, .awake);
        const elapsed: u64 = @intCast(@max(0, slot.started.durationTo(finished).nanoseconds));
        self.result.requests += 1;
        self.result.latency_sum_ns += elapsed;
        self.result.latency_max_ns = @max(self.result.latency_max_ns, elapsed);
        slot.stream = InFlight.no_stream;
        self.topUp(conn);
    }

    fn release(self: *Load, stream: u64) void {
        if (self.find(stream)) |slot| slot.stream = InFlight.no_stream;
    }

    fn find(self: *Load, stream: u64) ?*InFlight {
        for (self.slots) |*slot| {
            if (slot.stream == stream) return slot;
        }
        return null;
    }

    /// Fills every free slot. Requests are issued from inside a callback on purpose: the
    /// client's own flush follows the delivery on the same task, so the datagrams go out
    /// without a wakeup.
    fn topUp(self: *Load, conn: *http3.client.Connection) void {
        if (Io.Timestamp.now(self.io, .awake).nanoseconds >= self.deadline.nanoseconds) return;
        for (self.slots) |*slot| {
            if (slot.stream != InFlight.no_stream) continue;
            var fields: [6]qpack.FieldLine = undefined;
            const request = http3.connection.requestFields(
                "GET",
                "https",
                self.host,
                "/bench",
                &.{},
                &fields,
            );
            const stream = conn.request(self.gpa, request, true) catch {
                // `error.StreamLimitError` most of the time: the peer has not permitted
                // another stream yet. The slot stays free and `stream_credit` retries it,
                // which is the whole reason that event exists. Counted rather than hidden,
                // because the count is how the credit ceiling shows up in the results.
                self.result.refused += 1;
                return;
            };
            slot.stream = stream;
            slot.started = Io.Timestamp.now(self.io, .awake);
        }
    }
};

pub fn main(init: std.process.Init.Minimal) !void {
    var debug_allocator: std.heap.DebugAllocator(.{}) = .init;
    defer if (debug_allocator.deinit() == .leak) {
        log.err("benchmark leaked memory", .{});
        std.process.exit(1);
    };
    const gpa = debug_allocator.allocator();

    const config = try parseConfig(gpa, init.args);
    defer gpa.free(config.exe);
    switch (config.role) {
        .server => return runServer(gpa, config),
        .client => return runClient(gpa, config, null),
        .both => return runBoth(gpa, config),
    }
}

fn runBoth(gpa: std.mem.Allocator, config: Config) !void {
    var harness: Io.Threaded = .init(gpa, .{});
    defer harness.deinit();
    const harness_io = harness.io();

    const port = try freeUdpPort(harness_io);
    const port_text = try std.fmt.allocPrint(gpa, "{d}", .{port});
    defer gpa.free(port_text);
    const seconds_text = try std.fmt.allocPrint(gpa, "{d}", .{config.duration_seconds + 4});
    defer gpa.free(seconds_text);

    var child = try std.process.spawn(harness_io, .{
        .argv = &.{ config.exe, "server", port_text, seconds_text },
    });
    var reaped = false;
    defer if (!reaped) child.kill(harness_io);

    // A UDP socket accepts no connection, so there is nothing to probe: the client's own
    // handshake is the readiness check, and it retries for as long as the timeout allows.
    try harness_io.sleep(.fromMilliseconds(300), .awake);

    var client_config = config;
    client_config.port = port;
    var load_runtime = try backend.Runtime.init(gpa);
    defer load_runtime.deinit();
    try runClient(gpa, client_config, load_runtime.io());

    _ = child.wait(harness_io) catch {};
    reaped = true;
}

/// A UDP port nothing is bound to. Same trade as `http_bench`'s TCP version: racy in
/// principle, reliable in practice, and the right one for a benchmark.
fn freeUdpPort(io: Io) !u16 {
    var probe: Io.net.IpAddress = .{ .ip4 = .loopback(0) };
    var socket = try probe.bind(io, .{ .mode = .dgram });
    const chosen = socket.address.getPort();
    socket.close(io);
    return chosen;
}

fn runServer(gpa: std.mem.Allocator, config: Config) !void {
    var runtime = try backend.Runtime.init(gpa);
    defer runtime.deinit();
    const io = runtime.io();

    const identity = identity_mod.testRealIdentity();

    var server = try http3.server.Server.listen(.{
        .gpa = gpa,
        .io = io,
        .address = .{ .ip4 = .loopback(config.port) },
        .identity = &identity,
        .streams = .initFunction(buildStream),
        .token_key = .init(@splat(0x5a)),
    });
    defer server.deinit();

    log.info("{s}build: {t}", .{ server_prefix, @import("builtin").mode });
    log.info("{s}listening on udp {d}", .{ server_prefix, server.localAddress().getPort() });

    try io.sleep(.fromSeconds(@intCast(config.duration_seconds)), .awake);
    log.info("{s}{d} connections accepted, {d} requests seen, {d} answered", .{
        server_prefix,
        server.acceptedCount(),
        seen.load(.acquire),
        answered.load(.acquire),
    });
}

fn runClient(gpa: std.mem.Allocator, config: Config, provided_io: ?Io) !void {
    var runtime: ?backend.Runtime = if (provided_io == null) try backend.Runtime.init(gpa) else null;
    defer if (runtime) |*owned| owned.deinit();
    const io = provided_io orelse runtime.?.io();

    log.info("http/3 bench: {d} connections x {d} in flight, {d}s, udp {d}", .{
        config.connections,
        config.flight,
        config.duration_seconds,
        config.port,
    });

    const results = try gpa.alloc(Result, config.connections);
    defer gpa.free(results);
    @memset(results, .{});

    const loads = try gpa.alloc(Load, config.connections);
    defer gpa.free(loads);
    const clients = try gpa.alloc(?http3.client.Client, config.connections);
    defer gpa.free(clients);
    @memset(clients, null);

    const slot_storage = try gpa.alloc(InFlight, config.connections * config.flight);
    defer gpa.free(slot_storage);
    @memset(slot_storage, .{ .stream = InFlight.no_stream });

    const deadline = Io.Timestamp.now(io, .awake)
        .addDuration(.fromSeconds(@intCast(config.duration_seconds)));

    const address: Io.net.IpAddress = .{ .ip4 = .loopback(config.port) };
    const started = Io.Timestamp.now(io, .awake);

    for (loads, 0..) |*load, index| {
        load.* = .{
            .gpa = gpa,
            .io = io,
            .host = identity_mod.test_real_host,
            .slots = slot_storage[index * config.flight ..][0..config.flight],
            .deadline = deadline,
            .result = &results[index],
        };
        clients[index] = try http3.client.Client.connect(.{
            .gpa = gpa,
            .io = io,
            .address = address,
            .host = identity_mod.test_real_host,
            .verification = null,
            .delegate = .init(load, Load.on),
        });
    }
    defer for (clients) |*maybe| {
        if (maybe.*) |*client| client.deinit();
    };

    // The load runs on the endpoints' reader tasks; this task only waits for the clock. Every
    // result is written by exactly one reader task and read here only after `deinit` above has
    // stopped them, which is the same discipline the rest of the repository uses.
    while (Io.Timestamp.now(io, .awake).nanoseconds < deadline.nanoseconds) {
        try io.sleep(.fromMilliseconds(20), .awake);
    }
    const finished = Io.Timestamp.now(io, .awake);

    for (clients) |*maybe| {
        if (maybe.*) |*client| client.deinit();
        maybe.* = null;
    }

    var total: Result = .{};
    var established: usize = 0;
    for (results) |result| {
        total.requests += result.requests;
        total.latency_sum_ns += result.latency_sum_ns;
        total.latency_max_ns = @max(total.latency_max_ns, result.latency_max_ns);
        total.resets += result.resets;
        total.refused += result.refused;
        total.closed += result.closed;
        total.timed_out += result.timed_out;
        total.goaway += result.goaway;
        if (result.established) established += 1;
    }

    const elapsed_ns: u64 = @intCast(@max(1, started.durationTo(finished).nanoseconds));
    const elapsed_s = @as(f64, @floatFromInt(elapsed_ns)) / @as(f64, std.time.ns_per_s);
    const qps = @as(f64, @floatFromInt(total.requests)) / elapsed_s;
    const mean_us = if (total.requests == 0) 0.0 else @as(f64, @floatFromInt(total.latency_sum_ns)) /
        @as(f64, @floatFromInt(total.requests)) / 1000.0;

    log.info("elapsed:          {d:.2} s", .{elapsed_s});
    log.info("connections up:   {d} of {d}", .{ established, config.connections });
    log.info("requests:         {d} ({d:.0} req/s)", .{ total.requests, qps });
    log.info("latency mean:     {d:.0} us", .{mean_us});
    log.info("latency max:      {d:.0} us", .{
        @as(f64, @floatFromInt(total.latency_max_ns)) / 1000.0,
    });
    log.info("resets:           {d}", .{total.resets});
    log.info("credit refusals:  {d}", .{total.refused});
    if (total.closed + total.timed_out + total.goaway > 0) {
        log.info("stopped early:    {d} closed by peer, {d} idle timeouts, {d} goaway", .{
            total.closed,
            total.timed_out,
            total.goaway,
        });
    }
}

fn parseConfig(gpa: std.mem.Allocator, args: std.process.Args) !Config {
    var iterator = try std.process.Args.Iterator.initAllocator(args, gpa);
    defer iterator.deinit();

    var config: Config = .{};
    config.exe = try gpa.dupe(u8, iterator.next() orelse return error.NoExecutablePath);
    const first = iterator.next() orelse return config;

    if (std.mem.eql(u8, first, "server")) {
        config.role = .server;
        if (iterator.next()) |text| config.port = try std.fmt.parseInt(u16, text, 10);
        if (iterator.next()) |text| config.duration_seconds = try std.fmt.parseInt(u64, text, 10);
        return config;
    }
    if (std.mem.eql(u8, first, "client")) {
        config.role = .client;
        if (iterator.next()) |text| config.port = try std.fmt.parseInt(u16, text, 10);
        if (iterator.next()) |text| config.connections = try std.fmt.parseInt(usize, text, 10);
        if (iterator.next()) |text| config.flight = try std.fmt.parseInt(usize, text, 10);
        if (iterator.next()) |text| config.duration_seconds = try std.fmt.parseInt(u64, text, 10);
        if (config.port == 0) return error.PortRequired;
        if (config.connections == 0 or config.flight == 0) return error.InvalidConcurrency;
        return config;
    }

    config.connections = try std.fmt.parseInt(usize, first, 10);
    if (iterator.next()) |text| config.flight = try std.fmt.parseInt(usize, text, 10);
    if (iterator.next()) |text| config.duration_seconds = try std.fmt.parseInt(u64, text, 10);
    if (config.connections == 0 or config.flight == 0) return error.InvalidConcurrency;
    return config;
}
